// Vanilla JavaScript, no framework.
//
// Two jobs only:
//   1. Fill the Backend Trace panel that sits at the bottom of every page.
//   2. Send the upload form and the play requests, then describe what happened.


// The four places the trace panel is written into.
var requestBox = document.getElementById("trace-request");
var responseBox = document.getElementById("trace-response");
var dataBox = document.getElementById("trace-data");
var explanationList = document.getElementById("trace-explanation");


// Draw one trace object into the panel. Every other function ends by calling this.
function showTrace(trace) {
    requestBox.textContent = JSON.stringify(trace.request, null, 4);
    responseBox.textContent = JSON.stringify(trace.response, null, 4);
    dataBox.textContent = JSON.stringify(trace.data, null, 4);

    explanationList.innerHTML = "";
    for (var i = 0; i < trace.explanation.length; i++) {
        var item = document.createElement("li");
        item.textContent = trace.explanation[i];
        explanationList.appendChild(item);
    }
}


// On page load the trace describes the request that produced this very page.
// The server put it into the page as JSON inside a <script> tag.
var embedded = document.getElementById("backend-trace");
showTrace(JSON.parse(embedded.textContent));


// ---------------------------------------------------------------------------
// Play buttons (home page only)
//
// Clicking Play points the <audio> element at /songs/<filename>. The browser
// then sends a GET for that URL, which you can watch arrive in the terminal.
// ---------------------------------------------------------------------------

var playButtons = document.querySelectorAll(".play-button");

for (var b = 0; b < playButtons.length; b++) {
    playButtons[b].addEventListener("click", function (event) {
        var fileName = event.target.dataset.file;
        var url = "/songs/" + fileName;
        var player = event.target.parentElement.querySelector(".player");

        player.src = url;
        player.play();

        showTrace({
            request: {
                method: "GET",
                url: url,
                headers: {
                    "Accept": "audio/*",
                    "Range": "bytes=0- (the audio element asks for the file in pieces)"
                },
                body: "(a GET request has no body)"
            },
            response: {
                status: "HTTP 200",
                headers: {
                    "Content-Type": "audio/mpeg"
                },
                body: "Audio Stream"
            },
            data: {
                file_name: fileName
            },
            explanation: [
                "Play clicked, the audio element was pointed at " + url,
                "Browser sent GET " + url,
                "Python matched serve_song()",
                "No SQL was executed, this route reads a file from disk",
                "Backend read uploads/" + fileName + " and set Content-Type: audio/mpeg",
                "HTTP 200 returned with the mp3 bytes, the browser plays them"
            ]
        });
    });
}


// ---------------------------------------------------------------------------
// Upload form (upload page only)
//
// The form is sent with fetch() instead of a normal browser submit, so that the
// page can stay put and show the request and the response side by side.
// ---------------------------------------------------------------------------

var uploadForm = document.getElementById("upload-form");

if (uploadForm) {
    uploadForm.addEventListener("submit", function (event) {
        event.preventDefault();

        var creatorName = document.getElementById("creator_name").value;
        var songDescription = document.getElementById("song_description").value;
        var fileInput = document.getElementById("song_file");
        var chosenFile = fileInput.files[0];
        var messageBox = document.getElementById("upload-message");

        // FormData is what makes the browser build a multipart/form-data body:
        // three parts, each with its own name, the last one carrying the bytes.
        var formData = new FormData();
        formData.append("creator_name", creatorName);
        formData.append("song_description", songDescription);
        if (chosenFile) {
            formData.append("song_file", chosenFile);
        }

        var requestDescription = {
            method: "POST",
            url: "/api/upload",
            headers: {
                "Content-Type": "multipart/form-data; boundary=<generated by the browser>"
            },
            multipart_parts: [
                { name: "creator_name", value: creatorName },
                { name: "song_description", value: songDescription },
                {
                    name: "song_file",
                    filename: chosenFile ? chosenFile.name : null,
                    type: chosenFile ? chosenFile.type : null,
                    size_in_bytes: chosenFile ? chosenFile.size : null
                }
            ]
        };

        messageBox.textContent = "Uploading...";

        fetch("/api/upload", { method: "POST", body: formData })
            .then(function (response) {
                // Response headers are read here, before the body is parsed.
                var headers = {};
                response.headers.forEach(function (value, name) {
                    headers[name] = value;
                });

                return response.json().then(function (body) {
                    messageBox.textContent = body.message;

                    showTrace({
                        request: requestDescription,
                        response: {
                            status: "HTTP " + response.status,
                            headers: headers
                        },
                        data: body,
                        explanation: buildUploadExplanation(body, chosenFile)
                    });
                });
            });
    });
}


// The story of an upload, written out for the panel. It differs depending on
// whether the backend accepted the form or rejected it.
function buildUploadExplanation(body, chosenFile) {
    if (!body.success) {
        return [
            "Browser sent POST /api/upload with a multipart body",
            "Python matched upload_song()",
            "Form data was read, but something required was missing",
            "Validation failed, no file was saved and no SQL was executed",
            "HTTP 400 returned with success:false and a message"
        ];
    }

    return [
        "Browser sent POST /api/upload with a multipart body",
        "Python matched upload_song()",
        "Backend read creator_name, song_description and the file part",
        "File written to uploads/" + chosenFile.name,
        "SQL executed: INSERT INTO songs (creator_name, song_description, file_name) VALUES (?, ?, ?)",
        "SQLite affected 1 row and generated id " + body.data.song_id,
        "Response packed as {success, data, message} and returned as HTTP 200"
    ];
}
